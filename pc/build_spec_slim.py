"""
build_spec_slim.py — Build allégé SANS modèles whisper embarqués.
Les modèles sont téléchargés automatiquement au premier lancement via HuggingFace.
Output : dist/MeetNote-slim-<version>  (~300-400 MB au lieu de 3.2 GB)
"""

import os
import subprocess
import sys
import tempfile

from build_paths import (
    collecter_datas,
    composer_bilan,
    dist_dir_name,
    formater_datas,
    produire_archive,
)
from build_version import build_version_resource
from version import VERSION

# ─── Paths ───────────────────────────────────────────────────────────────────
SCRIPT_DIR  = os.path.dirname(os.path.abspath(__file__))
VENV        = os.path.join(os.path.dirname(os.path.dirname(SCRIPT_DIR)), ".venv")
SITE_PKG    = os.path.join(VENV, "Lib", "site-packages")

# ─── Datas : pas de modèles, uniquement les assets runtime ───────────────────
ALERTES = []  # reprises dans le bilan final, après le journal PyInstaller
datas_block = formater_datas(
    collecter_datas(SITE_PKG, journal=lambda m: print(f"[build_slim] {m}"),
                    alertes=ALERTES,
                    etape=os.path.join(tempfile.gettempdir(), "meetnote-slim-ffmpeg"))
)

# ─── Hidden imports (identiques au build complet) ────────────────────────────
hidden_imports = [
    "soundcard", "soundcard.mediafoundation",
    "sounddevice", "_sounddevice", "_sounddevice_data",
    "faster_whisper", "faster_whisper.audio", "faster_whisper.feature_extractor",
    "faster_whisper.tokenizer", "faster_whisper.transcribe",
    "faster_whisper.utils", "faster_whisper.vad",
    "ctranslate2", "tokenizers", "tokenizers.models", "tokenizers.normalizers",
    "tokenizers.pre_tokenizers", "tokenizers.processors", "tokenizers.decoders",
    "pystray", "pystray._win32",
    "PIL", "PIL.Image", "PIL.ImageDraw", "PIL.ImageFont", "PIL._imaging",
    "tkinter", "tkinter.ttk",
    "huggingface_hub", "huggingface_hub.file_download",
    "numpy", "av", "onnxruntime", "onnxruntime.capi", "cffi",
    "notion_push", "notion_api", "assistant_agenda", "assistant_audio",
    "assistant_fenetre", "assistant_notion", "config", "user_config", "fichier_json", "perf_profile", "modeles", "version", "history", "journal_app", "outlook_cal",
    "source_agenda", "teams_roster", "watchdog", "demarrage_windows", "soundfile", "_soundfile",
    "wave", "glob", "json", "collections", "dataclasses", "shutil",
    "scipy", "scipy.signal", "noisereduce", "debruitage",
    "pycaw", "pycaw.pycaw", "comtypes", "psutil",
    "win32com", "win32com.client", "pywintypes",
]
hidden_imports_str = ",\n    ".join(f"'{h}'" for h in hidden_imports)

# Modules volontairement absents du paquet (voir build_spec.py et PLAN.md, T029).
excludes = ['pandas', 'jupyter', 'IPython', 'PyQt5', 'wx', 'torch', 'numba', 'llvmlite']
excludes_str = ", ".join(f"'{e}'" for e in excludes)

# ─── Spec ────────────────────────────────────────────────────────────────────
ENTRY_POINT = os.path.join(SCRIPT_DIR, "meetnote-tray.py").replace("\\", "/")
DIST_NAME   = dist_dir_name(VERSION, slim=True)

# Ressource de version de l'exe (Propriétés → Détails), issue de version.py.
# Écrite dans le dossier temporaire du poste, pas dans le dépôt.
VERSION_FILE = os.path.join(tempfile.gettempdir(), "meetnote-slim.version.txt")
with open(VERSION_FILE, "w", encoding="utf-8") as f:
    f.write(build_version_resource(VERSION))
print(f"[build_slim] Version {VERSION} — ressource écrite : {VERSION_FILE}")

spec_content = f"""# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by build_spec_slim.py — do not edit manually

import sys
from PyInstaller.utils.hooks import collect_all

block_cipher = None

ct2_datas, ct2_binaries, ct2_hiddenimports = collect_all('ctranslate2')
sd_datas, sd_binaries, sd_hiddenimports   = collect_all('sounddevice')

a = Analysis(
    [r'{ENTRY_POINT}'],
    pathex=[r'{SCRIPT_DIR.replace(chr(92), "/")}'],
    binaries=ct2_binaries + sd_binaries,
    datas=[
{datas_block}
    ] + ct2_datas + sd_datas,
    hiddenimports=[
    {hidden_imports_str},
    ] + ct2_hiddenimports + sd_hiddenimports,
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[{excludes_str}],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='MeetNote',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    console=False,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
    icon=None,
    version=r'{VERSION_FILE}',
)

coll = COLLECT(
    exe,
    a.binaries,
    a.zipfiles,
    a.datas,
    strip=False,
    upx=False,
    upx_exclude=[],
    name='{DIST_NAME}',
)
"""

spec_path = os.path.join(SCRIPT_DIR, "meetnote-slim.spec")
with open(spec_path, "w", encoding="utf-8") as f:
    f.write(spec_content)
print(f"[build_slim] Wrote {spec_path}")

# ─── Run PyInstaller ──────────────────────────────────────────────────────────
print("[build_slim] Starting PyInstaller build (no models)...")
pyinstaller_exe = os.path.join(VENV, "Scripts", "pyinstaller.exe")
if not os.path.exists(pyinstaller_exe):
    pyinstaller_exe = "pyinstaller"

result = subprocess.run(
    [pyinstaller_exe, "--clean", "--noconfirm", spec_path],
    cwd=SCRIPT_DIR,
    capture_output=False,
)

if result.returncode != 0:
    print(f"\n[build_slim] FAILED (exit {result.returncode})")
    sys.exit(result.returncode)

dist_dir = os.path.join(SCRIPT_DIR, "dist", DIST_NAME)

# ─── Taille finale ───────────────────────────────────────────────────────────
total = sum(
    os.path.getsize(os.path.join(r, f))
    for r, _, files in os.walk(dist_dir)
    for f in files
)
count = sum(len(files) for _, _, files in os.walk(dist_dir))
print(f"\n[build_slim] SUCCESS — {dist_dir}")
print(f"[build_slim] {count} files, {total / 1024 / 1024:.1f} MB")

# ─── Zip pour GitHub Release ─────────────────────────────────────────────────
# COLLECT vide pc\dist\<DIST_NAME> avant d'y écrire (PyInstaller, --noconfirm) :
# ce dossier est déjà la sortie fraîche, il n'a pas de restes à comparer.
produire_archive(dist_dir, VERSION, os.path.dirname(dist_dir), slim=True,
                 journal=lambda m: print(f"[build_slim] {m}"), alertes=ALERTES)
for ligne in composer_bilan(ALERTES):
    print(f"[build_slim] {ligne}")
